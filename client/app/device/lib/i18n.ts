export const STAFF_DICTS: Record<StaffLang, StaffDict> = { en, fil, hi, ar, ur, ja, vi };

/** Each language named in itself, for the picker. */
export const STAFF_LANG_NAMES: Record<StaffLang, string> = {
  en: "English", fil: "Filipino", hi: "हिन्दी", ar: "العربية", ur: "اردو", ja: "日本語", vi: "Tiếng Việt",
};

/** Codes the roster may hold for the same language (staff_members.languages
    is free text: the seed writes "fil" for Maria and "tl" for Joy). Region
    tags reduce to their base first ("ja-JP" -> "ja", "vi-VN" -> "vi"). */
const ALIASES: Record<string, StaffLang> = {
  en: "en", fil: "fil", tl: "fil", tgl: "fil", fl: "fil", hi: "hi", ar: "ar", ur: "ur",
  ja: "ja", jpn: "ja", jp: "ja", vi: "vi", vie: "vi",
};

const RTL = new Set(["ar", "ur", "fa", "he", "ps", "ckb", "dv", "sd", "ug", "yi"]);

/** "fil-PH" -> "fil", "tl" -> "fil", "hi-IN" -> "hi"; null when unsupported. */
export function toStaffLang(code: string | null | undefined): StaffLang | null {
  if (!code) return null;
  const base = code.trim().toLowerCase().split(/[-_]/)[0];
  return ALIASES[base] ?? null;
}

export interface LangSources {
  /** The worker's own pick on this device (the header picker). */
  stored?: string | null;
  /** The server's word for the worker's reading language (staff_members.languages[0]). */
  server?: string | null;
  /** navigator.languages. */
  browser?: readonly string[] | null;
}

/** An explicit pick wins, then the roster language, then the browser, then English. */
export function resolveStaffLang({ stored, server, browser }: LangSources): StaffLang {
  return toStaffLang(stored) ?? toStaffLang(server) ?? (browser ?? []).map(toStaffLang).find(Boolean) ?? "en";
}

export function staffDir(lang: string | null | undefined): "rtl" | "ltr" {
  const base = (lang ?? "").toLowerCase().split(/[-_]/)[0];
  return RTL.has(base) ? "rtl" : "ltr";
}

export type StaffT = (key: StaffKey, vars?: Record<string, string | number>) => string;

/** A lookup for one language: its dictionary, then English, then the key. */
export function staffT(lang: string | null | undefined): StaffT {
  const dict = STAFF_DICTS[toStaffLang(lang) ?? "en"];
  return (key, vars) => {
    const raw = dict[key] ?? en[key] ?? key;
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
  };
}

const STATES = new Set(["scheduled", "new", "reopened", "assigned", "acknowledged", "in_progress", "completed", "cancelled"]);

/** A request state in the worker's words; an unknown state reads as itself. */
export function stateText(state: string, t: StaffT): string {
  return STATES.has(state) ? t(`state.${state}` as StaffKey) : state.replace(/_/g, " ");
}

/** The {placeholders} a string uses, sorted (the test compares languages). */
export function placeholders(s: string): string[] {
  return Array.from(s.matchAll(/\{(\w+)\}/g), m => m[1]).sort();
}

// ─── Intl helpers (the browser and Node both ship full ICU) ─────────────

/** A language code named in the reader's language ("ar" in Hindi: "अरबी"). */
export function languageName(code: string | null | undefined, uiLang: string): string | null {
  if (!code) return null;
  const base = code.trim().toLowerCase().split(/[-_]/)[0];
  try {
    const name = new Intl.DisplayNames([uiLang, "en"], { type: "language" }).of(base);
    if (name && name.toLowerCase() !== base) return name;
  } catch { /* old engine or a code ICU does not know */ }
  return base.toUpperCase();
}

/** "3m ago" / "3 मि॰ पहले"; under a minute reads job.justNow. */
export function agoText(ts: number, now: number, uiLang: string, t: StaffT): string {
  const s = Math.max(0, Math.round((now - ts) / 1000));
  if (!Number.isFinite(s) || s < 60) return t("job.justNow");
  const [n, unit]: [number, Intl.RelativeTimeFormatUnit] =
    s < 3600 ? [Math.floor(s / 60), "minute"] : s < 86_400 ? [Math.floor(s / 3600), "hour"] : [Math.floor(s / 86_400), "day"];
  try {
    return new Intl.RelativeTimeFormat(uiLang, { numeric: "always", style: "narrow" }).format(-n, unit);
  } catch {
    return `${n}${unit[0]} ago`;
  }
}

/** A short duration, rounded up and never under a minute: "3m", "1h 5m", "3 मि". */
export function durationText(ms: number, uiLang: string): string {
  const total = Math.max(1, Math.ceil(ms / 60_000));
  const fmt = (n: number, unit: "hour" | "minute") => {
    try {
      return new Intl.NumberFormat(uiLang, { style: "unit", unit, unitDisplay: "narrow" }).format(n);
    } catch {
      return `${n}${unit === "hour" ? "h" : "m"}`;
    }
  };
  if (total < 60) return fmt(total, "minute");
  const h = Math.floor(total / 60), m = total % 60;
  return m ? `${fmt(h, "hour")} ${fmt(m, "minute")}` : fmt(h, "hour");
}
