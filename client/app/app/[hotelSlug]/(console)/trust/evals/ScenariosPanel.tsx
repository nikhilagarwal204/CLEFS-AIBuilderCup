"use client";

/* ═══════════════════════════════════════════════════════════════════════
   Scenarios: the standard set (shipped YAML, read-only), the auto-KB suite
   (two paraphrases per approved KB entry, regenerated by "Sync from KB")
   and the hotel's own custom scenarios. A custom scenario is a guest
   message or two plus expectations in the DSL documented in the Trust
   README; the server validates it strictly, so a typo is refused with a
   message rather than silently never failing.
   ═══════════════════════════════════════════════════════════════════════ */

import { useState } from "react";
import { api, useApi } from "../../../../../lib/api";
import { useSession } from "../../../../../lib/session";
import {
  Badge, Button, Card, EmptyState, Field, Input, Modal, Segmented, Select, Table, Textarea, useToast, type Column,
} from "../../../../../ui";
import { catLabel, errText, EVAL_CATEGORY_LABEL, trustApi } from "../lib";
import type { AutoKbSync, EvalScenario, Suite } from "../types";

type SuiteFilter = "all" | Suite;
const SUITE_LABEL: Record<Suite, string> = { standard: "Standard", auto_kb: "Auto-KB", custom: "Custom" };

export default function ScenariosPanel({ slug }: { slug: string }) {
  const toast = useToast();
  const { can } = useSession();
  const canManage = can("trust.evals.manage");
  const [suite, setSuite] = useState<SuiteFilter>("all");
  const list = useApi<EvalScenario[]>(
    trustApi(slug, `/evals/scenarios${suite === "all" ? "" : `?suite=${suite}`}`), [slug, suite]);
  const [syncing, setSyncing] = useState(false);
  const [creating, setCreating] = useState(false);

  async function syncKb() {
    setSyncing(true);
    try {
      const r = await api.post<AutoKbSync>(trustApi(slug, "/evals/auto-kb/sync"));
      toast.success("Auto-KB suite synced",
        `${r.entries} entries: ${r.created} new, ${r.retired} retired${r.errors.length ? `, ${r.errors.length} errors` : ""}.`);
      list.reload();
    } catch (e) {
      toast.error("Sync failed", errText(e));
    } finally {
      setSyncing(false);
    }
  }

  async function deactivate(s: EvalScenario) {
    try {
      await api.del(trustApi(slug, `/evals/scenarios/${s.id}`));
      toast.success("Scenario switched off", "Past results keep it.");
      list.reload();
    } catch (e) {
      toast.error("Couldn't switch it off", errText(e));
    }
  }

  const columns: Column<EvalScenario>[] = [
    {
      key: "title", header: "Scenario",
      render: s => (
        <span>
          {s.title || s.key}
          <span className="cx-faint trs-small" style={{ display: "block" }}>{s.turns[0]?.text?.slice(0, 90) ?? ""}</span>
        </span>
      ),
    },
    { key: "category", header: "Category", render: s => catLabel(s.category) },
    { key: "language", header: "Lang", width: 60, render: s => <span className="trs-mono">{s.language}</span> },
    {
      key: "suite", header: "Suite", hideOnMobile: true,
      render: s => <Badge tone={s.suite === "custom" ? "gold" : "neutral"}>{SUITE_LABEL[s.suite] ?? s.suite}</Badge>,
    },
    {
      key: "act", header: "", align: "right",
      render: s => (canManage && s.suite === "custom" && s.active
        ? <Button size="sm" variant="ghost" onClick={() => deactivate(s)}>Switch off</Button>
        : s.flaky ? <Badge tone="warn" title="Decided by best of 3">flaky</Badge> : null),
    },
  ];

  return (
    <Card
      title="Scenarios"
      padded={false}
      actions={
        <div className="cx-row">
          <Segmented size="sm" ariaLabel="Suite" value={suite} onChange={setSuite}
                     options={[{ value: "all", label: "All" }, { value: "standard", label: "Standard" },
                               { value: "auto_kb", label: "Auto-KB" }, { value: "custom", label: "Custom" }]} />
          {canManage && <Button size="sm" loading={syncing} onClick={syncKb}>Sync from KB</Button>}
          {canManage && <Button size="sm" variant="primary" onClick={() => setCreating(true)}>New scenario</Button>}
        </div>
      }
    >
      {list.error && !list.data
        ? <EmptyState title="Couldn't load scenarios" body={list.error.message} />
        : (
          <Table caption="Evaluation scenarios" columns={columns} rows={list.data ?? []} rowKey={s => s.id}
                 loading={list.loading}
                 empty={<EmptyState title="No scenarios in this suite"
                                    body={suite === "auto_kb" ? "Approve KB entries, then sync." : "Nothing here yet."} />} />
        )}
      <NewScenarioModal slug={slug} open={creating} onClose={() => setCreating(false)} onSaved={list.reload} />
    </Card>
  );
}

// ─── New custom scenario ─────────────────────────────────────────────────

const EXAMPLE = `{
  "must_escalate": true,
  "must_not_contain": ["guarantee"],
  "language": "en",
  "max_sentences": 3
}`;

function NewScenarioModal({ slug, open, onClose, onSaved }: {
  slug: string;
  open: boolean;
  onClose: () => void;
  onSaved: () => void;
}) {
  const toast = useToast();
  const [key, setKey] = useState("");
  const [title, setTitle] = useState("");
  const [category, setCategory] = useState("general");
  const [language, setLanguage] = useState("en");
  const [turns, setTurns] = useState("");
  const [expect, setExpect] = useState(EXAMPLE);
  const [err, setErr] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  async function save() {
    setErr(null);
    let expectations: Record<string, unknown>;
    try {
      expectations = JSON.parse(expect || "{}");
    } catch {
      setErr("Expectations must be valid JSON.");
      return;
    }
    const lines = turns.split("\n").map(t => t.trim()).filter(Boolean);
    if (!key.trim() || lines.length === 0) {
      setErr("A key and at least one guest message are needed.");
      return;
    }
    setBusy(true);
    try {
      await api.post(trustApi(slug, "/evals/scenarios"), {
        key: key.trim(), title: title.trim() || null, category, language, turns: lines, expectations,
      });
      toast.success("Scenario added", "It runs with the next evaluation.");
      onSaved();
      onClose();
      setKey(""); setTitle(""); setTurns(""); setExpect(EXAMPLE);
    } catch (e) {
      setErr(errText(e));
    } finally {
      setBusy(false);
    }
  }

  return (
    <Modal open={open} onClose={onClose} dismissible={!busy} size="lg" title="New custom scenario"
           footer={<>
             <Button variant="ghost" onClick={onClose} disabled={busy}>Cancel</Button>
             <Button variant="primary" loading={busy} onClick={save}>Add scenario</Button>
           </>}>
      <div className="cx-stack" style={{ gap: 12 }}>
        <div className="cx-grid cx-grid--2">
          <Field label="Key" hint="Unique, e.g. late_checkout_vip" required>
            <Input value={key} onChange={e => setKey(e.target.value)} maxLength={120} />
          </Field>
          <Field label="Title">
            <Input value={title} onChange={e => setTitle(e.target.value)} maxLength={200} />
          </Field>
          <Field label="Category">
            <Select value={category} onChange={e => setCategory(e.target.value)}
                    options={Object.entries(EVAL_CATEGORY_LABEL).map(([value, label]) => ({ value, label }))} />
          </Field>
          <Field label="Reply language">
            <Select value={language} onChange={e => setLanguage(e.target.value)}
                    options={[{ value: "en", label: "English" }, { value: "ar", label: "Arabic" },
                              { value: "ru", label: "Russian" }, { value: "hi", label: "Hindi" }]} />
          </Field>
        </div>
        <Field label="Guest messages" hint="One per line; each line is one guest turn (up to 10)." required>
          <Textarea rows={3} value={turns} onChange={e => setTurns(e.target.value)} />
        </Field>
        <Field label="Expectations (JSON)"
               hint="Keys: must_call, must_not_call, must_escalate, must_not_contain, must_contain_any, language, max_sentences, no_unlisted_prices, emergency_numbers, grounded_in_kb, bound_room, rubric.">
          <Textarea code rows={7} value={expect} onChange={e => setExpect(e.target.value)} />
        </Field>
        {err && <p className="trs-small" style={{ color: "var(--cx-bad)" }} role="alert">{err}</p>}
      </div>
    </Modal>
  );
}
